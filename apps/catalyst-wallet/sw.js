// Catalyst Bank Service Worker — PWA Offline Support
const CACHE = 'catalyst-bank-v1';
const ASSETS = [
  '/apps/catalyst-wallet/mobile-app.html',
  '/apps/catalyst-wallet/verify-face.html',
  '/apps/catalyst-wallet/transfer-system.html',
  '/apps/catalyst-wallet/index.html',
];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)));
  self.skipWaiting();
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys =>
    Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))
  ));
  self.clients.claim();
});

self.addEventListener('fetch', e => {
  e.respondWith(
    caches.match(e.request).then(cached =>
      cached || fetch(e.request).then(resp => {
        if (resp.ok) {
          const clone = resp.clone();
          caches.open(CACHE).then(c => c.put(e.request, clone));
        }
        return resp;
      })
    )
  );
});
